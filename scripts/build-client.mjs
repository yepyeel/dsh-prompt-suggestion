#!/usr/bin/env node
// Bundle the client/ modules into the classic lazy-CJS script DSH loads.
//
// DSH injects client bundles as classic scripts that call
// window.__ModuleLoader__.load({ id, factory }); it does not resolve npm/browser
// imports from a published plugin. esbuild keeps the module graph readable in
// client/ and emits the one self-contained client.js the loader expects.

import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const outfile = path.join(root, 'client.js')

const result = await build({
  absWorkingDir: root,
  entryPoints: ['client/entry.cjs'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react'],
  write: false,
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
})

const body = result.outputFiles[0].text
const banner = `// Generated by scripts/build-client.mjs. Edit files under client/ instead.
//
// Client half of the prompt-suggestion bundle: a ghost prediction inside the
// resident composer, plus its settings page.

window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} }
    var exports = module.exports
`
const footer = `
    return module.exports
  },
})
`

await writeFile(outfile, banner + body + footer)
console.log(`client.js: ${Buffer.byteLength(banner + body + footer)} bytes`)
