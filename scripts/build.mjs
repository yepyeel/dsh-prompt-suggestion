#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build, context } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const check = process.argv.includes('--check')
const watch = process.argv.includes('--watch')
if (check && watch) throw new Error('--check and --watch are mutually exclusive')

const banner = `// Generated by scripts/build.mjs. Edit src/client/ instead.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory(require) {\n    var module = { exports: {} }\n    var exports = module.exports\n`
const footer = '\n    return module.exports\n  },\n})'

function options(client) {
  return {
    absWorkingDir: root,
    entryPoints: [client ? 'src/client/entry.cjs' : 'src/host/index.ts'],
    outfile: client ? 'build/client.js' : 'build/index.js',
    bundle: true,
    format: client ? 'cjs' : 'esm',
    platform: client ? 'browser' : 'node',
    target: client ? 'es2020' : 'node22',
    external: client ? ['react'] : ['@deepseek-ai/schemastery'],
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    legalComments: 'none',
    charset: 'utf8',
    banner: {
      js: client
        ? banner
        : '// Generated by scripts/build.mjs. Edit src/host/ or src/shared/ instead.',
    },
    footer: client ? { js: footer } : undefined,
    write: watch,
    logLevel: 'warning',
  }
}

if (watch) {
  const contexts = await Promise.all([context(options(false)), context(options(true))])
  await Promise.all(contexts.map((instance) => instance.watch()))
  console.log('Watching Host and Client sources. Reload the plugin or restart DSH after a build.')
  const stop = async () => {
    await Promise.all(contexts.map((instance) => instance.dispose()))
    process.exit(0)
  }
  process.once('SIGINT', stop)
  process.once('SIGTERM', stop)
} else {
  for (const client of [false, true]) {
    const result = await build(options(client))
    const output = result.outputFiles[0]
    const outputName = path.relative(root, output.path)
    if (check) {
      let existing
      try {
        existing = await readFile(output.path)
      } catch {
        /* Missing output is stale too. */
      }
      if (!existing?.equals(output.contents))
        throw new Error(`${outputName} is stale. Run pnpm build and commit both generated bundles.`)
    } else {
      await mkdir(path.dirname(output.path), { recursive: true })
      await writeFile(output.path, output.contents)
    }
    console.log(`${outputName}: ${check ? 'verified' : `${output.contents.length} bytes`}`)
  }
}
